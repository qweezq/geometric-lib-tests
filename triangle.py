def area(a, h):
    '''
    Принимает сторону a и высоту h, опущенную на нее, возвращает площадь треугольника.
    Параметры:
        a (float/int): сторона треугольника
        h (float/int): высота, опущенная на сторону a
    Возвращаемое значение:
        float: площадь треугольника
    Пример вызова:
        area(2, 2) -> 2.0
    '''
    return a * h / 2


def perimeter(a, b, c):
    '''
    Принимает длины сторон треугольника a, b, c, возвращает его периметр.
    Параметры:
        a (float/int): первая сторона
        b (float/int): вторая сторона
        c (float/int): третья сторона
    Возвращаемое значение:
        float/int: периметр треугольника
    Пример вызова:
        perimeter(3, 4, 5) -> 12
    '''
    return a + b + c