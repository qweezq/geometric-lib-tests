def area(a, b):
    '''
    Принимает стороны прямоугольника a и b, возвращает его площадь.
    Параметры:
        a (float/int): первая сторона прямоугольника
        b (float/int): вторая сторона прямоугольника
    Возвращаемое значение:
        float/int: площадь прямоугольника
    Пример вызова:
        area(5, 5) -> 25
    '''
    return a * b


def perimeter(a, b):
    '''
    Принимает стороны прямоугольника a и b, возвращает его периметр.

    Параметры:
        a (float/int): первая сторона прямоугольника
        b (float/int): вторая сторона прямоугольника

    Возвращаемое значение:
        float/int: периметр прямоугольника

    Пример вызова:
        perimeter(5, 5) -> 20
    '''
    return 2 * (a + b)