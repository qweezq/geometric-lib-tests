def area(a):
    '''
    Принимает длину стороны квадрата a, возвращает его площадь.
    Параметры:
        a (float/int): длина стороны квадрата
    Возвращаемое значение:
        float/int: площадь квадрата
    Пример вызова:
        area(5) -> 25
    '''
    return a * a


